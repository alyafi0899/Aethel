import '../models.dart';

@Deprecated('Use InboxRepository with clinic_inbox.')
abstract class NotificationsRepository {
  Future<List<NotificationItem>> fetchNotifications();
  Future<void> sendNotification(
      {required String title, required String body, String? category});
}

@Deprecated('Use SupabaseClinicalRepository; legacy notification API removed.')
class SupabaseNotificationsRepository implements NotificationsRepository {
  SupabaseNotificationsRepository({Object? client});

  @override
  Future<List<NotificationItem>> fetchNotifications() =>
      Future.error(UnsupportedError(
        'Legacy notifications API is disabled. Use the clinic inbox.',
      ));

  @override
  Future<void> sendNotification(
          {required String title, required String body, String? category}) =>
      Future.error(UnsupportedError(
        'Notifications are generated by authorized clinical workflow RPCs.',
      ));
}
